"""Build LibFlightTime DBC data from WotLK 3.3.5 Taxi*.dbc files.

Usage: python tools/generate_flight_times.py C:/path/to/DBFilesClient
"""

from __future__ import annotations

import math
import pathlib
import struct
import sys
from collections import defaultdict


ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "libs" / "LibFlightTime-1.0" / "data.lua"
# TrinityCore 3.3.5 flies the taxi spline at 32 units/second. The older
# Leatrix-derived table was calibrated near 30 and is not authoritative for
# this server (Stormwind -> Lakeshire landed about five seconds early).
FLIGHT_SPEED = 32.0


def read_dbc(path: pathlib.Path):
    raw = path.read_bytes()
    if raw[:4] != b"WDBC":
        raise ValueError(f"Not a WDBC file: {path}")
    count, fields, record_size, string_size = struct.unpack_from("<4I", raw, 4)
    if record_size != fields * 4 or len(raw) != 20 + count * record_size + string_size:
        raise ValueError(f"Unexpected DBC layout: {path}")
    records = [struct.unpack_from(f"<{fields}I", raw, 20 + i * record_size) for i in range(count)]
    return records, raw[20 + count * record_size :]


def dbc_string(pool: bytes, offset: int) -> str:
    if not offset:
        return ""
    return pool[offset : pool.index(b"\0", offset)].decode("utf-8")


def flt(bits: int) -> float:
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def spline_length(points: list[tuple[float, float, float]]) -> float:
    """Approximate TrinityCore's flying Catmull-Rom spline (3 steps/segment)."""
    if len(points) < 2:
        return 0.0
    length = 0.0
    for index in range(len(points) - 1):
        p0 = points[max(0, index - 1)]
        p1 = points[index]
        p2 = points[index + 1]
        p3 = points[min(len(points) - 1, index + 2)]
        previous = p1
        for step in (1, 2, 3):
            t = step / 3.0
            weights = (
                -0.5 * t**3 + t**2 - 0.5 * t,
                1.5 * t**3 - 2.5 * t**2 + 1,
                -1.5 * t**3 + 2 * t**2 + 0.5 * t,
                0.5 * t**3 - 0.5 * t**2,
            )
            current = tuple(sum(p[axis] * weight for p, weight in zip((p0, p1, p2, p3), weights))
                            for axis in range(3))
            length += math.dist(previous, current)
            previous = current
    return length


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main(directory: pathlib.Path) -> None:
    nodes, names = read_dbc(directory / "TaxiNodes.dbc")
    paths, _ = read_dbc(directory / "TaxiPath.dbc")
    path_nodes, _ = read_dbc(directory / "TaxiPathNode.dbc")
    if len(nodes[0]) != 24 or len(paths[0]) != 4 or len(path_nodes[0]) != 11:
        raise ValueError("Expected WotLK 3.3.5 Taxi DBC layout")

    points = defaultdict(list)
    for row in path_nodes:
        points[row[1]].append(row)
    for rows in points.values():
        rows.sort(key=lambda row: row[2])

    lines = [
        "-- Generated by tools/generate_flight_times.py from WotLK Taxi*.dbc.",
        "-- Names are ruRU; times use 3D flight spline length / 32 units per second.",
        "SarychUIFlightTimeData = { nodes = {",
    ]
    for row in sorted(nodes, key=lambda row: row[0]):
        name = dbc_string(names, row[13])  # ruRU in the 16-locales name block
        if name:
            # DBC mount columns are Horde, then Alliance.
            mask = (1 if row[23] else 0) + (2 if row[22] else 0)
            lines.append(f"  [{row[0]}] = {{{lua_string(name)}, {mask}}},")
    lines.append("}, edges = {")

    edges = defaultdict(dict)
    for path_id, source, target, _cost in paths:
        route = points.get(path_id)
        if not route or len(route) < 2:
            continue
        length = 0.0
        map_points = []
        current_map = None
        for row in route:
            if row[3] != current_map:
                length += spline_length(map_points)
                map_points = []
                current_map = row[3]
            map_points.append((flt(row[4]), flt(row[5]), flt(row[6])))
        length += spline_length(map_points)
        if length:
            edges[source][target] = round(length / FLIGHT_SPEED, 2)
    for source in sorted(edges):
        members = ", ".join(f"[{target}]={value:.2f}" for target, value in sorted(edges[source].items()))
        lines.append(f"  [{source}] = {{{members}}},")
    lines.append("} }")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUTPUT}: {len(nodes)} nodes, {sum(map(len, edges.values()))} directed paths")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]))
